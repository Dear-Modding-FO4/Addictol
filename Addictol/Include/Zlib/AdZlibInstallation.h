	inline constexpr size_t ZLIB_INSTALL_IMAGE_SIZE = 0x1FD0;
	// Empty means every entry and all six independent anchor checks matched.
	inline std::optional<std::string_view> ValidateZlibInstallation(std::span<const uint8_t> a_image) noexcept
	{
		for (const auto& entry : ZLIB_ENTRIES)
			if (!ZlibInflate::Matches(a_image, entry.offset, entry.prologue))
				return entry.name;
		if (!ZlibInflate::ValidateContract(a_image))
			return "inflate anchor contract";
		return std::nullopt;
	}
	// Returns the rejection reason; empty means every entry and anchor matched and the commit succeeded.
	template<class Commit>
	std::optional<std::string_view> InstallValidatedZlib(std::span<const uint8_t> a_image, Commit&& a_commit)
	{
		if (const auto rejected = ValidateZlibInstallation(a_image))
			return rejected;
		if (!a_commit())
			return "transaction rejected";
		return std::nullopt;
	}
	void LogInvalidOwnedZlibState() noexcept;
	template<class Owned, class Original, class Function>
	int32_t RouteZlibStream(const ZlibInflate::Stream* a_stream, Original&& a_original, Function&& a_owned) noexcept
	{
		if (!ZlibOwnedState::IsTagged(a_stream))
			return a_original();
		if (!Owned::IsOwned(a_stream))
		{
			LogInvalidOwnedZlibState();
			return INFLATE_STREAM_ERROR;
		}
		return a_owned();
	}
